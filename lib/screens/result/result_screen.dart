import 'dart:typed_data';

import 'package:flutter/material.dart';
import 'package:image_picker/image_picker.dart';

import '../report/report_screen.dart';

class ResultScreen extends StatelessWidget {
  final Uint8List imageBytes;
  final XFile imageFile;
  final Map<String, dynamic> result;

  const ResultScreen({
    super.key,
    required this.imageBytes,
    required this.imageFile,
    required this.result,
  });

  int get dopiGrade {
    return int.tryParse(result['dopi_grade']?.toString() ?? '0') ?? 0;
  }

  String get classification {
    return result['classification']?.toString() ?? 'Unknown';
  }

  double get confidence {
    return double.tryParse(result['confidence_percent']?.toString() ?? '0') ??
        0;
  }

  Map<String, dynamic> get probabilities {
    final value = result['probabilities'];

    if (value is Map) {
      return Map<String, dynamic>.from(value);
    }

    return {};
  }

  Color get gradeColor {
    switch (dopiGrade) {
      case 0:
        return const Color(0xFF16A34A);

      case 1:
        return const Color(0xFFB7791F);

      case 2:
        return const Color(0xFFA65F3E);

      case 3:
        return const Color(0xFF7F1D1D);

      default:
        return const Color(0xFF3154B5);
    }
  }

  String get gradeDescription {
    switch (dopiGrade) {
      case 0:
        return 'Pink gingival tissue with no clinical pigmentation.';

      case 1:
        return 'Mild light-brown gingival pigmentation.';

      case 2:
        return 'Medium-brown or mixed pink/brown pigmentation.';

      case 3:
        return 'Deep brown or blue/black gingival pigmentation.';

      default:
        return 'Assessment result generated by the AI model.';
    }
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      backgroundColor: const Color(0xFFF6F8FC),

      appBar: AppBar(
        elevation: 0,
        backgroundColor: const Color(0xFFF6F8FC),
        foregroundColor: const Color(0xFF1E293B),
        centerTitle: true,

        title: const Text(
          'Analysis Result',
          style: TextStyle(fontSize: 22, fontWeight: FontWeight.w700),
        ),
      ),

      body: SafeArea(
        child: SingleChildScrollView(
          padding: const EdgeInsets.fromLTRB(20, 12, 20, 30),

          child: Center(
            child: ConstrainedBox(
              constraints: const BoxConstraints(maxWidth: 1200),

              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,

                children: [
                  // ==================================================
                  // IMAGE
                  // ==================================================
                  Center(
                    child: ConstrainedBox(
                      constraints: const BoxConstraints(
                        maxWidth: 900,
                        maxHeight: 300,
                      ),

                      child: Container(
                        width: double.infinity,
                        height: 290,

                        padding: const EdgeInsets.all(8),

                        decoration: BoxDecoration(
                          color: Colors.white,

                          borderRadius: BorderRadius.circular(22),

                          border: Border.all(color: const Color(0xFFE2E8F0)),

                          boxShadow: [
                            BoxShadow(
                              color: Colors.black.withValues(alpha: 0.06),
                              blurRadius: 18,
                              offset: const Offset(0, 7),
                            ),
                          ],
                        ),

                        child: ClipRRect(
                          borderRadius: BorderRadius.circular(16),

                          child: Image.memory(imageBytes, fit: BoxFit.contain),
                        ),
                      ),
                    ),
                  ),

                  const SizedBox(height: 26),

                  // ==================================================
                  // TITLE
                  // ==================================================
                  const Text(
                    'AI Assessment',
                    style: TextStyle(
                      fontSize: 28,
                      fontWeight: FontWeight.w800,
                      color: Color(0xFF172033),
                    ),
                  ),

                  const SizedBox(height: 5),

                  const Text(
                    'Gingival melanin pigmentation analysis',
                    style: TextStyle(fontSize: 15, color: Color(0xFF64748B)),
                  ),

                  const SizedBox(height: 20),

                  // ==================================================
                  // MAIN RESULT
                  // ==================================================
                  Container(
                    width: double.infinity,
                    padding: const EdgeInsets.all(28),

                    decoration: BoxDecoration(
                      gradient: LinearGradient(
                        colors: [
                          gradeColor.withValues(alpha: 0.13),
                          Colors.white,
                        ],
                      ),

                      borderRadius: BorderRadius.circular(24),

                      border: Border.all(
                        color: gradeColor.withValues(alpha: 0.25),
                      ),

                      boxShadow: [
                        BoxShadow(
                          color: Colors.black.withValues(alpha: 0.05),
                          blurRadius: 18,
                          offset: const Offset(0, 7),
                        ),
                      ],
                    ),

                    child: Column(
                      children: [
                        const Text(
                          'DOPI Grade',
                          style: TextStyle(
                            fontSize: 16,
                            color: Color(0xFF64748B),
                            fontWeight: FontWeight.w500,
                          ),
                        ),

                        const SizedBox(height: 5),

                        Text(
                          '$dopiGrade',
                          style: TextStyle(
                            fontSize: 64,
                            height: 1,
                            fontWeight: FontWeight.w800,
                            color: gradeColor,
                          ),
                        ),

                        const SizedBox(height: 13),

                        Container(
                          padding: const EdgeInsets.symmetric(
                            horizontal: 18,
                            vertical: 9,
                          ),

                          decoration: BoxDecoration(
                            color: gradeColor.withValues(alpha: 0.12),

                            borderRadius: BorderRadius.circular(30),
                          ),

                          child: Text(
                            classification,
                            style: TextStyle(
                              fontSize: 17,
                              fontWeight: FontWeight.w700,
                              color: gradeColor,
                            ),
                          ),
                        ),

                        const SizedBox(height: 14),

                        Text(
                          gradeDescription,
                          textAlign: TextAlign.center,

                          style: const TextStyle(
                            fontSize: 14,
                            height: 1.5,
                            color: Color(0xFF64748B),
                          ),
                        ),
                      ],
                    ),
                  ),

                  const SizedBox(height: 18),

                  // ==================================================
                  // CONFIDENCE
                  // ==================================================
                  Container(
                    width: double.infinity,
                    padding: const EdgeInsets.all(22),

                    decoration: BoxDecoration(
                      color: Colors.white,
                      borderRadius: BorderRadius.circular(20),

                      border: Border.all(color: const Color(0xFFE2E8F0)),

                      boxShadow: [
                        BoxShadow(
                          color: Colors.black.withValues(alpha: 0.04),
                          blurRadius: 15,
                          offset: const Offset(0, 6),
                        ),
                      ],
                    ),

                    child: Column(
                      children: [
                        Row(
                          mainAxisAlignment: MainAxisAlignment.spaceBetween,

                          children: [
                            const Text(
                              'AI Confidence',
                              style: TextStyle(
                                fontSize: 16,
                                color: Color(0xFF64748B),
                                fontWeight: FontWeight.w500,
                              ),
                            ),

                            Text(
                              '${confidence.toStringAsFixed(2)}%',
                              style: const TextStyle(
                                fontSize: 22,
                                fontWeight: FontWeight.w800,
                                color: Color(0xFF16A34A),
                              ),
                            ),
                          ],
                        ),

                        const SizedBox(height: 14),

                        ClipRRect(
                          borderRadius: BorderRadius.circular(20),

                          child: LinearProgressIndicator(
                            value: (confidence / 100).clamp(0.0, 1.0),

                            minHeight: 10,

                            backgroundColor: const Color(0xFFE2E8F0),

                            valueColor: const AlwaysStoppedAnimation<Color>(
                              Color(0xFF16A34A),
                            ),
                          ),
                        ),
                      ],
                    ),
                  ),

                  const SizedBox(height: 18),

                  // ==================================================
                  // INTERPRETATION
                  // ==================================================
                  Container(
                    width: double.infinity,
                    padding: const EdgeInsets.all(22),

                    decoration: BoxDecoration(
                      color: Colors.white,
                      borderRadius: BorderRadius.circular(20),

                      border: Border.all(color: const Color(0xFFE2E8F0)),
                    ),

                    child: Column(
                      crossAxisAlignment: CrossAxisAlignment.start,

                      children: [
                        const Row(
                          children: [
                            Icon(Icons.info_outline, color: Color(0xFF3154B5)),

                            SizedBox(width: 10),

                            Text(
                              'Interpretation',
                              style: TextStyle(
                                fontSize: 18,
                                fontWeight: FontWeight.w700,
                                color: Color(0xFF1E293B),
                              ),
                            ),
                          ],
                        ),

                        const SizedBox(height: 12),

                        Text(
                          _interpretation(),
                          style: const TextStyle(
                            fontSize: 15,
                            height: 1.5,
                            color: Color(0xFF64748B),
                          ),
                        ),
                      ],
                    ),
                  ),

                  const SizedBox(height: 24),

                  // ==================================================
                  // BUTTONS
                  // ==================================================
                  SizedBox(
                    width: double.infinity,

                    child: ElevatedButton.icon(
                      onPressed: () {
                        Navigator.push(
                          context,

                          MaterialPageRoute(
                            builder: (_) => ReportScreen(
                              imageBytes: imageBytes,
                              imageFile: imageFile,
                              result: result,
                            ),
                          ),
                        );
                      },

                      icon: const Icon(Icons.description_outlined),

                      label: const Text('View Detailed Report'),

                      style: ElevatedButton.styleFrom(
                        minimumSize: const Size(double.infinity, 54),

                        backgroundColor: const Color(0xFF3154B5),

                        foregroundColor: Colors.white,

                        elevation: 3,

                        shape: RoundedRectangleBorder(
                          borderRadius: BorderRadius.circular(15),
                        ),
                      ),
                    ),
                  ),

                  const SizedBox(height: 12),

                  SizedBox(
                    width: double.infinity,

                    child: OutlinedButton.icon(
                      onPressed: () {
                        Navigator.popUntil(context, (route) => route.isFirst);
                      },

                      icon: const Icon(Icons.camera_alt_outlined),

                      label: const Text('Analyze Another Image'),

                      style: OutlinedButton.styleFrom(
                        minimumSize: const Size(double.infinity, 52),

                        foregroundColor: const Color(0xFF3154B5),

                        side: const BorderSide(color: Color(0xFF8BA4FF)),

                        shape: RoundedRectangleBorder(
                          borderRadius: BorderRadius.circular(15),
                        ),
                      ),
                    ),
                  ),

                  const SizedBox(height: 20),

                  const Center(
                    child: Text(
                      'Research and educational prototype — not a substitute for professional clinical evaluation.',
                      textAlign: TextAlign.center,
                      style: TextStyle(
                        fontSize: 12,
                        height: 1.4,
                        color: Color(0xFF94A3B8),
                      ),
                    ),
                  ),
                ],
              ),
            ),
          ),
        ),
      ),
    );
  }

  String _interpretation() {
    switch (dopiGrade) {
      case 0:
        return 'No clinical gingival melanin pigmentation was detected according to the DOPI classification.';

      case 1:
        return 'Mild gingival melanin pigmentation was detected according to the DOPI classification.';

      case 2:
        return 'Moderate gingival melanin pigmentation was detected according to the DOPI classification.';

      case 3:
        return 'Severe gingival melanin pigmentation was detected according to the DOPI classification.';

      default:
        return 'The AI model generated an assessment, but the classification could not be interpreted.';
    }
  }
}
